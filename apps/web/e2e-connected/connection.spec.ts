import { test, expect } from "@playwright/test";
import { mkdir } from "node:fs/promises";
test("connected UI uses local session, server catalogue and SSE, then cancels and logs out", async ({ page }) => {
  const requests: string[] = [], errors: string[] = [];
  page.on("request", r => requests.push(r.url())); page.on("pageerror", e => errors.push(e.message));
  await page.goto("/");
  await page.getByLabel("Mot de passe local").fill("Local-e2e-password-123");
  await page.getByRole("button", { name: "Ouvrir mon espace" }).click();
  await expect(page.getByLabel("Modèle de conversation")).toHaveValue("-1002");
  await expect(page.getByLabel("Modèle de conversation")).toContainText("Modèle réel test");
  await page.getByLabel("Votre message").fill("Bonjour");
  await page.getByRole("button", { name: "Envoyer le message" }).click();
  await expect(page.getByLabel("Réponse FranceStudent")).toContainText("Bonjour été");
  await expect(page.getByRole("button", { name: "Arrêter la réponse" })).toBeVisible();
  await page.getByRole("button", { name: "Arrêter la réponse" }).click();
  await expect(page.getByText("Réponse arrêtée", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Réessayer", exact: true }).click();
  await expect(page.getByRole("button", { name: "Arrêter la réponse" })).not.toBeVisible({ timeout: 15000 });
  await page.getByLabel("Votre message").fill("Continue"); await page.getByRole("button", { name: "Envoyer le message" }).click();
  await expect(page.getByLabel("Réponse FranceStudent")).toHaveCount(2);
  await expect(page.getByRole("button", { name: "Arrêter la réponse" })).not.toBeVisible({ timeout: 15000 });
  await page.reload(); await expect(page.getByLabel("Réponse FranceStudent")).toHaveCount(2);
  await mkdir("../../artifacts/web-connected", { recursive: true });
  await page.screenshot({ path: "../../artifacts/web-connected/desktop-dark.png", animations: "disabled" });
  await page.getByRole("button", { name: /Paramètres/ }).click();
  await page.getByRole("button", { name: "Clair", exact: true }).click(); await page.keyboard.press("Escape");
  await page.screenshot({ path: "../../artifacts/web-connected/desktop-light.png", animations: "disabled" });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator(".composer textarea")).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "../../artifacts/web-connected/mobile-light.png", animations: "disabled" });
  await page.getByRole("button", { name: "Ouvrir la navigation" }).click();
  await page.getByRole("button", { name: /Paramètres/ }).click();
  await page.getByRole("button", { name: "Sombre", exact: true }).click(); await page.keyboard.press("Escape");
  await page.screenshot({ path: "../../artifacts/web-connected/mobile-dark.png", animations: "disabled" });
  await page.getByRole("button", { name: "Ouvrir la navigation" }).click();
  await page.getByRole("button", { name: "Déconnexion locale" }).click();
  await expect(page.getByLabel("Mot de passe local")).toBeVisible();
  await page.setViewportSize({ width: 390, height: 390 });
  await page.getByRole("button", { name: "Ouvrir mon espace" }).scrollIntoViewIfNeeded();
  await expect(page.getByRole("button", { name: "Ouvrir mon espace" })).toBeInViewport();
  expect(requests.some(url => url.includes("francestudent.ai") || url.includes("api/auth/api-token"))).toBe(false);
  const local = await page.evaluate(() => JSON.stringify(localStorage)); expect(local).not.toMatch(/secret-jwt|secret-session|next-auth/);
  expect(errors).toEqual([]);
});
